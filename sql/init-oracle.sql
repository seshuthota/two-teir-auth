-- ============================================================
-- TABLES
-- ============================================================

CREATE TABLE auth_client (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id VARCHAR2(100) NOT NULL UNIQUE,
    client_name VARCHAR2(255) NOT NULL,
    client_secret_hash VARCHAR2(500) NOT NULL,
    status VARCHAR2(30) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE auth_scope (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope_name VARCHAR2(100) NOT NULL UNIQUE,
    description VARCHAR2(500),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE auth_client_scope (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id VARCHAR2(100) NOT NULL,
    scope_name VARCHAR2(100) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (client_id, scope_name)
);

CREATE TABLE auth_api_scope_mapping (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    http_method VARCHAR2(20) NOT NULL,
    api_pattern VARCHAR2(255) NOT NULL,
    required_scope VARCHAR2(100) NOT NULL,
    status VARCHAR2(30) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE auth_token_audit (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id VARCHAR2(100) NOT NULL,
    token_id VARCHAR2(100),
    event_type VARCHAR2(50) NOT NULL,
    ip_address VARCHAR2(100),
    user_agent VARCHAR2(500),
    status VARCHAR2(30),
    failure_reason VARCHAR2(500),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

